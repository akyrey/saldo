-- Phase 2 schema, copied from docs/ARCHITECTURE.md sections 5.1, 5.2, 5.5 (events only) and 5.6.
-- Never edit this file once merged; add a new migration instead.

-- 5.1 Identity
CREATE TABLE currencies (
    code            TEXT PRIMARY KEY CHECK (length(code) = 3 AND code = upper(code)),
    name            TEXT NOT NULL,
    symbol          TEXT NOT NULL,
    decimal_places  INTEGER NOT NULL CHECK (decimal_places BETWEEN 0 AND 8)
) STRICT;

CREATE TABLE households (
    id                TEXT PRIMARY KEY,
    name              TEXT NOT NULL,
    primary_currency  TEXT NOT NULL REFERENCES currencies (code),
    timezone          TEXT NOT NULL DEFAULT 'UTC',
    created_at        TEXT NOT NULL,
    updated_at        TEXT NOT NULL
) STRICT;

CREATE TABLE users (
    id             TEXT PRIMARY KEY,
    email          TEXT NOT NULL UNIQUE COLLATE NOCASE,
    display_name   TEXT NOT NULL,
    password_hash  TEXT NOT NULL,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL
) STRICT;

CREATE TABLE household_members (
    household_id  TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    user_id       TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role          TEXT NOT NULL CHECK (role IN ('owner', 'member')),
    created_at    TEXT NOT NULL,
    PRIMARY KEY (household_id, user_id)
) STRICT;

-- Browser/desktop sessions and personal access tokens share one table.
-- Only the SHA-256 of the token is stored.
CREATE TABLE sessions (
    id            TEXT PRIMARY KEY,
    user_id       TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    household_id  TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    kind          TEXT NOT NULL CHECK (kind IN ('session', 'token')),
    name          TEXT,
    token_hash    TEXT NOT NULL UNIQUE,
    created_at    TEXT NOT NULL,
    last_used_at  TEXT,
    expires_at    TEXT
) STRICT;
CREATE INDEX sessions_user ON sessions (user_id);

-- 5.2 Ledger
CREATE TABLE accounts (
    id                    TEXT PRIMARY KEY,
    household_id          TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    owner_user_id         TEXT REFERENCES users (id) ON DELETE SET NULL,   -- NULL = joint
    name                  TEXT NOT NULL,
    type                  TEXT NOT NULL CHECK (type IN ('asset', 'expense', 'revenue', 'liability', 'equity')),
    equity_role           TEXT CHECK (equity_role IN ('opening_balance', 'reconciliation')),
    asset_role            TEXT CHECK (asset_role IN ('default', 'shared', 'savings', 'credit_card', 'cash_wallet')),
    liability_type        TEXT CHECK (liability_type IN ('loan', 'debt', 'mortgage')),
    liability_direction   TEXT CHECK (liability_direction IN ('i_owe', 'owed_to_me')),
    interest_rate         TEXT,                                            -- decimal string, percent
    interest_period       TEXT CHECK (interest_period IN ('daily', 'weekly', 'monthly', 'quarterly', 'half_year', 'yearly')),
    currency_code         TEXT NOT NULL REFERENCES currencies (code),
    iban                  TEXT,
    bic                   TEXT,
    account_number        TEXT,
    virtual_balance_minor INTEGER NOT NULL DEFAULT 0,
    include_net_worth     INTEGER NOT NULL DEFAULT 1 CHECK (include_net_worth IN (0, 1)),
    active                INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    sort_order            INTEGER NOT NULL DEFAULT 0,
    notes                 TEXT,
    created_at            TEXT NOT NULL,
    updated_at            TEXT NOT NULL,
    UNIQUE (household_id, id),
    UNIQUE (household_id, type, name),
    CHECK ((type = 'equity') = (equity_role IS NOT NULL)),
    CHECK (asset_role IS NULL OR type = 'asset'),
    CHECK (liability_type IS NULL OR type = 'liability')
) STRICT;
CREATE UNIQUE INDEX accounts_one_equity_per_role
    ON accounts (household_id, equity_role) WHERE equity_role IS NOT NULL;

CREATE TABLE categories (
    id            TEXT PRIMARY KEY,
    household_id  TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    notes         TEXT,
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL,
    UNIQUE (household_id, name)
) STRICT;

CREATE TABLE tags (
    id            TEXT PRIMARY KEY,
    household_id  TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    name          TEXT NOT NULL,
    description   TEXT,
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL,
    UNIQUE (household_id, name)
) STRICT;

CREATE TABLE transaction_groups (
    id                  TEXT PRIMARY KEY,
    household_id        TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    title               TEXT,
    created_by_user_id  TEXT REFERENCES users (id) ON DELETE SET NULL,
    recurrence_id       TEXT,          -- set when generated by a recurrence (FK added in Phase 5)
    recurrence_date     TEXT,
    created_at          TEXT NOT NULL,
    updated_at          TEXT NOT NULL,
    UNIQUE (household_id, id),
    UNIQUE (recurrence_id, recurrence_date)   -- a recurrence fires at most once per date
) STRICT;

CREATE TABLE splits (
    id                      TEXT PRIMARY KEY,
    household_id            TEXT NOT NULL,
    group_id                TEXT NOT NULL,
    position                INTEGER NOT NULL,
    kind                    TEXT NOT NULL CHECK (kind IN ('withdrawal', 'deposit', 'transfer', 'opening_balance', 'reconciliation')),
    date                    TEXT NOT NULL,
    description             TEXT NOT NULL,
    source_account_id       TEXT NOT NULL,
    destination_account_id  TEXT NOT NULL,
    amount_minor            INTEGER NOT NULL CHECK (amount_minor > 0),
    currency_code           TEXT NOT NULL REFERENCES currencies (code),
    foreign_amount_minor    INTEGER CHECK (foreign_amount_minor > 0),
    foreign_currency_code   TEXT REFERENCES currencies (code),
    category_id             TEXT REFERENCES categories (id) ON DELETE SET NULL,
    budget_id               TEXT,      -- FK to budgets added in Phase 5
    bill_id                 TEXT,      -- FK to bills added in Phase 5
    reconciled              INTEGER NOT NULL DEFAULT 0 CHECK (reconciled IN (0, 1)),
    notes                   TEXT,
    meta                    TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(meta)),
    created_at              TEXT NOT NULL,
    updated_at              TEXT NOT NULL,
    UNIQUE (household_id, id),
    UNIQUE (group_id, position),
    FOREIGN KEY (household_id, group_id) REFERENCES transaction_groups (household_id, id) ON DELETE CASCADE,
    FOREIGN KEY (household_id, source_account_id) REFERENCES accounts (household_id, id),
    FOREIGN KEY (household_id, destination_account_id) REFERENCES accounts (household_id, id),
    CHECK (source_account_id <> destination_account_id),
    CHECK ((foreign_amount_minor IS NULL) = (foreign_currency_code IS NULL)),
    CHECK (foreign_currency_code IS NULL OR foreign_currency_code <> currency_code)
) STRICT;
CREATE INDEX splits_household_date ON splits (household_id, date);
CREATE INDEX splits_source_date ON splits (source_account_id, date);
CREATE INDEX splits_destination_date ON splits (destination_account_id, date);
CREATE INDEX splits_category ON splits (category_id);
CREATE INDEX splits_budget ON splits (budget_id);
CREATE INDEX splits_bill ON splits (bill_id);

CREATE TABLE split_tags (
    split_id  TEXT NOT NULL REFERENCES splits (id) ON DELETE CASCADE,
    tag_id    TEXT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (split_id, tag_id)
) STRICT;
CREATE INDEX split_tags_tag ON split_tags (tag_id);

-- File content lives on disk at <data dir>/attachments/<sha256>.
CREATE TABLE attachments (
    id               TEXT PRIMARY KEY,
    household_id     TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    attachable_type  TEXT NOT NULL CHECK (attachable_type IN ('split', 'account', 'bill', 'budget', 'piggy_bank', 'tag')),
    attachable_id    TEXT NOT NULL,
    filename         TEXT NOT NULL,
    title            TEXT,
    mime_type        TEXT NOT NULL,
    size_bytes       INTEGER NOT NULL,
    sha256           TEXT NOT NULL,
    notes            TEXT,
    created_at       TEXT NOT NULL
) STRICT;
CREATE INDEX attachments_target ON attachments (attachable_type, attachable_id);

-- 5.5 Events (append-only)
-- Append-only. seq gives a total order; consumers remember the last seq they handled.
CREATE TABLE events (
    seq            INTEGER PRIMARY KEY AUTOINCREMENT,
    id             TEXT NOT NULL UNIQUE,
    household_id   TEXT NOT NULL REFERENCES households (id),
    event_type     TEXT NOT NULL,                 -- e.g. 'transaction.created'
    entity_type    TEXT NOT NULL,
    entity_id      TEXT NOT NULL,
    actor_user_id  TEXT,
    origin         TEXT NOT NULL CHECK (origin IN ('api', 'import', 'scheduler', 'rule', 'system')),
    payload        TEXT NOT NULL CHECK (json_valid(payload)),
    occurred_at    TEXT NOT NULL
) STRICT;
CREATE INDEX events_household ON events (household_id, seq);
CREATE INDEX events_entity ON events (entity_type, entity_id);

CREATE TRIGGER events_no_update BEFORE UPDATE ON events
BEGIN SELECT RAISE(ABORT, 'events is append-only'); END;
CREATE TRIGGER events_no_delete BEFORE DELETE ON events
BEGIN SELECT RAISE(ABORT, 'events is append-only'); END;

-- 5.6 Import
-- Maps an ID in an external system to the local row. This is what makes imports idempotent.
CREATE TABLE external_refs (
    household_id  TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    source        TEXT NOT NULL,                  -- 'firefly-iii'
    entity_type   TEXT NOT NULL,                  -- 'account', 'transaction_group', 'split', ...
    external_id   TEXT NOT NULL,
    local_id      TEXT NOT NULL,
    updated_at    TEXT NOT NULL,
    PRIMARY KEY (household_id, source, entity_type, external_id)
) STRICT;
CREATE INDEX external_refs_local ON external_refs (entity_type, local_id);

CREATE TABLE import_runs (
    id            TEXT PRIMARY KEY,
    household_id  TEXT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    source        TEXT NOT NULL,
    status        TEXT NOT NULL CHECK (status IN ('running', 'succeeded', 'failed')),
    summary       TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(summary)),
    started_at    TEXT NOT NULL,
    finished_at   TEXT
) STRICT;
